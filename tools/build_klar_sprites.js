#!/usr/bin/env node
/**
 * Klar-lampan sprite packer.
 *
 * Converts the shared Argus mascot PNGs (assets/img/*.png) + the hand icon to
 * small RGB565A8 blobs sized for the T-Dongle's 160x80 screen, and emits
 * firmware-klar/src/klar_sprites.h.
 *
 * Reuses the exact resize + background key-out pipeline from
 * build_argus_sprites.js (floodfill the near-white background to alpha), just at
 * a firmware-friendly size and with a non-square hand sprite.
 *
 * Blob layout per sprite (what the firmware's blit expects):
 *   w*h RGB565 pixels (little-endian) then w*h alpha bytes.
 *
 * Usage:  node tools/build_klar_sprites.js
 */

const fs = require("node:fs");
const path = require("node:path");
const sharp = require("sharp");
const { PNG } = require("pngjs");

const SRC_DIR = path.resolve(__dirname, "..", "assets", "img");
const ICON_DIR = path.resolve(__dirname, "..", "assets");
const OUT_FW = path.resolve(__dirname, "..", "firmware-klar", "src", "klar_sprites.h");

// name -> source PNG -> square target size (px). Faces are the 6 expressions
// Argus already ships; "hand" is the raised/waving hand.
const FACE = 64;
const SPRITES = [
  { name: "happy",     dir: SRC_DIR,  file: "happy.png",     w: FACE, h: FACE },
  { name: "looking",   dir: SRC_DIR,  file: "looking.png",   w: FACE, h: FACE },
  { name: "flirt",     dir: SRC_DIR,  file: "flirt.png",     w: FACE, h: FACE },
  { name: "buffeld",   dir: SRC_DIR,  file: "buffeld.png",   w: FACE, h: FACE },
  { name: "surprised", dir: SRC_DIR,  file: "surprised.png", w: FACE, h: FACE },
  { name: "angry",     dir: SRC_DIR,  file: "angry.png",     w: FACE, h: FACE },
  { name: "hand",      dir: ICON_DIR, file: "icon_hand.png", w: 28,   h: 28   },
];

function rgb565(r, g, b) {
  return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3);
}

// Floodfill from the four corners, erasing connected near-white pixels to alpha.
// Whites inside the character (eye dots, helmet highlights) are ringed by dark
// navy and never reached, so they stay opaque. (Same as build_argus_sprites.js.)
function keyOutBackground(rgba, w, h, threshold = 220) {
  const total = w * h;
  const visited = new Uint8Array(total);
  const stack = [];
  const tryPush = (x, y) => {
    if (x < 0 || x >= w || y < 0 || y >= h) return;
    const idx = y * w + x;
    if (visited[idx]) return;
    const o = idx * 4;
    if (Math.min(rgba[o], rgba[o + 1], rgba[o + 2]) < threshold) return;
    visited[idx] = 1;
    stack.push(x, y);
  };
  tryPush(0, 0); tryPush(w - 1, 0); tryPush(0, h - 1); tryPush(w - 1, h - 1);
  while (stack.length) {
    const y = stack.pop();
    const x = stack.pop();
    tryPush(x + 1, y); tryPush(x - 1, y); tryPush(x, y + 1); tryPush(x, y - 1);
  }
  for (let i = 0; i < total; i++) {
    if (visited[i]) rgba[i * 4 + 3] = 0;
  }
}

async function resizeToBuffer(srcPath, w, h) {
  const { data, info } = await sharp(srcPath)
    .resize(w, h, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  keyOutBackground(data, info.width, info.height);
  return { data, w: info.width, h: info.height };
}

function toRgb565a8(raw) {
  const { data, w, h } = raw;
  const total = w * h;
  const color = Buffer.alloc(total * 2);
  const alpha = Buffer.alloc(total);
  for (let i = 0; i < total; i++) {
    const c = rgb565(data[i * 4], data[i * 4 + 1], data[i * 4 + 2]);
    color[i * 2] = c & 0xFF;
    color[i * 2 + 1] = (c >> 8) & 0xFF;
    alpha[i] = data[i * 4 + 3];
  }
  return Buffer.concat([color, alpha]);
}

function emitArray(name, blob) {
  const symbol = `klar_sprite_${name}_data`;
  let out = `static const uint8_t ${symbol}[${blob.length}] = {\n    `;
  const lines = [];
  for (let i = 0; i < blob.length; i += 16) {
    const row = [];
    for (let j = 0; j < 16 && i + j < blob.length; j++) {
      row.push("0x" + blob[i + j].toString(16).padStart(2, "0").toUpperCase());
    }
    lines.push(row.join(", "));
  }
  out += lines.join(",\n    ") + "\n};\n";
  return { out, symbol };
}

async function main() {
  if (!fs.existsSync(SRC_DIR)) throw new Error(`Missing ${SRC_DIR}`);
  fs.mkdirSync(path.dirname(OUT_FW), { recursive: true });

  let header = "";
  header += "// Generated by tools/build_klar_sprites.js. Do not edit by hand.\n";
  header += "// Mascot sprites for the Klar-lampan, RGB565A8 (planar: w*h RGB565\n";
  header += "// little-endian, then w*h alpha bytes). Blit with sprite_blit().\n";
  header += "#pragma once\n#include <stdint.h>\n\n";
  header += "typedef struct {\n";
  header += "    const char *name;\n";
  header += "    const uint8_t *data;\n";
  header += "    uint16_t w;\n    uint16_t h;\n";
  header += "} klar_sprite_t;\n\n";

  const entries = [];
  for (const sp of SPRITES) {
    const srcPath = path.join(sp.dir, sp.file);
    if (!fs.existsSync(srcPath)) { console.warn(`SKIP ${sp.name}: missing ${srcPath}`); continue; }
    const raw = await resizeToBuffer(srcPath, sp.w, sp.h);
    const blob = toRgb565a8(raw);
    const { out, symbol } = emitArray(sp.name, blob);
    header += out + "\n";
    entries.push({ name: sp.name, symbol, w: raw.w, h: raw.h });
    console.log(`packed ${sp.name}  ${raw.w}x${raw.h}  ${(blob.length / 1024).toFixed(1)} KB`);
  }

  header += `#define KLAR_SPRITE_COUNT ${entries.length}\n`;
  header += "static const klar_sprite_t klar_sprites[KLAR_SPRITE_COUNT] = {\n";
  for (const e of entries) header += `    {"${e.name}", ${e.symbol}, ${e.w}, ${e.h}},\n`;
  header += "};\n";

  fs.writeFileSync(OUT_FW, header);
  console.log(`\nWrote ${OUT_FW}  (${(header.length / 1024).toFixed(1)} KB source)`);
}

main().catch((e) => { console.error(e); process.exit(1); });
